    z."Дата_запису",
    d."Ліцензія" AS "Ліцензія_лікаря",
    d."ПІБ" AS "ПІБ_лікаря",
    d."Спеціалізація",
    p."Номер мед. картки",
    p."ПІБ" AS "ПІБ_пацієнта"
FROM "Запис" z
INNER JOIN "Лікар" d ON z."Ліцензія_лікаря" = d."Ліцензія"
INNER JOIN "Пацієнт" p ON z."Номер_пацієнта" = p."Номер мед. картки"
WHERE d."Спеціалізація" LIKE %s
  AND p."ПІБ" LIKE %s
  AND z."Дата_запису" BETWEEN %s AND %s
ORDER BY z."Дата_запису" DESC
LIMIT 100;
