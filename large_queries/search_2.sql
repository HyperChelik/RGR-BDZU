SELECT
    diag."Дата_Захворювання",
    p."Номер мед. картки",
    p."ПІБ" AS "ПІБ_пацієнта",
    h."Код" AS "Код_хвороби",
    h."Назва" AS "Назва_хвороби",
    l."Ліцензія_лікаря" AS "Рекомендований_лікар"
FROM "Діагноз" diag
INNER JOIN "Пацієнт" p ON diag."Номер_пацієнта" = p."Номер мед. картки"
INNER JOIN "Хвороба" h ON diag."Код_хвороби" = h."Код"
LEFT JOIN "Лікування" l ON h."Код" = l."Код_хвороби"
WHERE h."Назва" LIKE %s
  AND diag."Дата_Захворювання" BETWEEN %s AND %s
ORDER BY diag."Дата_Захворювання" DESC
LIMIT 100;
